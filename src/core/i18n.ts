const dict: Record<Locale, Dict> = { en, tr };

export type MsgKey = keyof typeof en;
export const hasKey = (k: string): k is MsgKey => k in en;
export const t = (l: Locale, k: MsgKey, vars: Record<string, string | number> = {}) =>
  dict[l][k].replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? ''));
/** Label for a category id: built-in ones are translated, custom ones shown as-is. */
export const categoryLabel = (l: Locale, c: string) => {
  const k = `cat_${c}`;
  return hasKey(k) ? t(l, k) : c.replace(/-/g, ' ');
};
